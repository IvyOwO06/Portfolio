const isRepositoryPage = window.location.pathname.endsWith('/repos.html');

function setPortfolioLanguage(language) {
    const selected = portfolioTranslations[language] ? language : 'nl';
    const labels = portfolioTranslations[selected];

    document.documentElement.lang = selected;
    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const translation = labels[element.dataset.i18n];
        if (translation) element.innerHTML = translation;
    });

    document.querySelectorAll('[data-language]').forEach((button) => {
        button.setAttribute('aria-pressed', String(button.dataset.language === selected));
    });
    document.querySelectorAll('.language-switch').forEach((switcher) => {
        switcher.setAttribute('aria-label', selected === 'nl' ? 'Kies taal' : 'Choose language');
    });
    document.querySelectorAll('.nav').forEach((nav) => {
        nav.setAttribute('aria-label', selected === 'nl' ? 'Hoofdnavigatie' : 'Main navigation');
    });

    document.title = isRepositoryPage
        ? (selected === 'nl' ? 'GitHub-repositories — Sam Delhaye' : 'GitHub Repositories — Sam Delhaye')
        : (selected === 'nl' ? 'Sam Delhaye — Portfolio' : 'Sam Delhaye — Developer Portfolio');

    const description = document.querySelector('meta[name="description"]');
    if (description) {
        description.content = isRepositoryPage
            ? (selected === 'nl' ? 'GitHub-repositories van Sam Delhaye.' : 'GitHub repositories by Sam Delhaye.')
            : (selected === 'nl'
                ? 'Portfolio van Sam Delhaye: webontwikkeling, experimenten en uitgelichte projecten.'
                : "Sam Delhaye's portfolio: web development, experiments, and selected projects.");
    }

    try {
        localStorage.setItem('portfolio-language', selected);
    } catch (error) {
        // The page still works with Dutch as the default if storage is unavailable.
    }
}

document.querySelectorAll('[data-language]').forEach((button) => {
    button.addEventListener('click', () => setPortfolioLanguage(button.dataset.language));
});

let savedLanguage = 'nl';
try {
    savedLanguage = localStorage.getItem('portfolio-language') || 'nl';
} catch (error) {
    // Keep the Dutch default if storage is unavailable.
}
setPortfolioLanguage(savedLanguage);
